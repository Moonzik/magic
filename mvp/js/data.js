// 60 甲子纳音五行（每 2 同）：0木 1火 2土 3金 4水
const NAYIN_WU = [
  3, 3, 1, 1, 0, 0, 3, 3, 4, 4, 1, 1, 4, 4, 2, 2, 3, 3, 0, 0,
  3, 3, 1, 1, 0, 0, 4, 4, 3, 3, 1, 1, 2, 2, 0, 0, 3, 3, 2, 2,
  4, 4, 1, 1, 0, 0, 3, 3, 4, 4, 2, 2, 3, 3, 0, 0, 4, 4, 1, 1
];
// 纳音五行 → 五行局数：水二(4) 木三(0) 金四(3) 土五(2) 火六(1)
const WU_JU = { 4: 2, 0: 3, 3: 4, 2: 5, 1: 6 };
const JU_NAME = { 2: '水二局', 3: '木三局', 4: '金四局', 5: '土五局', 6: '火六局' };

function gzIndexOf(gan, zhi) { for (let i = 0; i < 60; i++) if (i % 10 === gan && i % 12 === zhi) return i; return -1; }
function isYangBranch(zi) { return zi % 2 === 0; } // 子0丑1… 阳支=偶数索引

// 排紫微命盘（简化趣味版）
function computeZiwei(year, month, day, hour, gender) {
  // 年柱（立春≈2/4 为界）
  let yFor = year;
  if (month < 2 || (month === 2 && day < 4)) yFor = year - 1;
  const yGZ = ((yFor - 4) % 60 + 60) % 60;
  const yGan = yGZ % 10, yZhi = yGZ % 12;

  const mbIdx = monthBranchIndex(month, day);          // 月支索引 0=寅…11=丑
  const hbIdx = (hour != null && !isNaN(hour)) ? hourBranchIndex(hour) : null; // 0=子…11=亥
  const M = mbIdx + 1;                                  // 月序 1..12（寅=1）
  const T = (hbIdx != null ? hbIdx : 0) + 1;            // 时序 1..12（子=1）

  // 命宫地支序（寅=1…丑=12）
  let ming = (M + T) <= 14 ? (14 - M - T) : (26 - M - T);
  const mingZhiIdx = (ming + 1) % 12;                   // ZHI 索引
  const mingGan = (((yGan % 5) * 2 + 2) + (ming - 1)) % 10;  // 五虎遁

  // 命宫干支纳音 → 五行局
  const mingGZ = gzIndexOf(mingGan, mingZhiIdx);
  const ju = WU_JU[NAYIN_WU[mingGZ]];

  // 紫微落宫（寅=1…丑=12）：rem = 日%局；紫微从寅宫逆数 rem 宫
  let rem = day % ju; if (rem === 0) rem = ju;
  let ziwei = 2 - rem; while (ziwei < 1) ziwei += 12;
  let tianfu = ziwei + 6; if (tianfu > 12) tianfu -= 12;  // 紫府对宫

  // 紫微落宫阴阳 → 紫微系顺/逆；天府系方向相反
  const ziYang = isYangBranch((ziwei + 1) % 12);
  const ziSys = ['紫微', '天机', '太阳', '武曲', '天同', '廉贞'];
  const fuSys = ['天府', '太阴', '贪狼', '巨门', '天相', '天梁', '七杀', '破军'];
  const starAt = {};
  function place(sys, base, forward) {
    sys.forEach((s, k) => {
      let p = base + (forward ? k : -k);
      p = ((p - 1) % 12 + 12) % 12 + 1;
      starAt[s] = p;
    });
  }
  place(ziSys, ziwei, ziYang);
  place(fuSys, tianfu, !ziYang);

  // 四化标注（取年干）：某星在某宫则标 禄/权/科/忌
  const sihuaMap = ZI_SIHUA[yGan];
  function sihuaOf(star) {
    const out = [];
    ['禄', '权', '科', '忌'].forEach(k => { if (sihuaMap[k] === star) out.push(k); });
    return out;
  }

  // 十二宫（命宫起顺时针）
  const houses = ZI_HOUSES.map((h, idx) => {
    const zhiSeq = ((ming - 1 + idx) % 12 + 12) % 12 + 1;   // 1..12
    const zhiIdx = (zhiSeq + 1) % 12;
    const stars = Object.keys(starAt).filter(s => starAt[s] === zhiSeq)
      .map(s => ({ name: s, sihua: sihuaOf(s) }));
    return { name: h.name, desc: h.desc, zhi: ZHI[zhiIdx], stars };
  });

  const mingStars = houses[0].stars.map(s => s.name);

  return {
    yearGan: yGan, yearZhi: yZhi,
    mingGan, mingZhi: ZHI[mingZhiIdx],
    ju, juName: JU_NAME[ju] || (ju + '局'),
    ziweiZhi: ZHI[(ziwei + 1) % 12], tianfuZhi: ZHI[(tianfu + 1) % 12],
    houses, mingStars, sihua: sihuaMap, gender
  };
}
// 命宫总论（温柔、非宿命）
function getZiweiSummary(res) {
  const stars = res.mingStars.length ? res.mingStars : ['空宫'];
  const starText = stars.map(s => `「${s}」${ZI_STARS[s] || ''}`).join('；');
  const lines = [];
  lines.push(`你的命宫坐${res.mingZhi}，${stars.length ? '主星为' + starText : '本宫无主星，气质更随环境与相处而显'}。`);
  lines.push(`命盘属${res.juName}，是这一生的底色与节奏——它不定义你，只映照你天生的质地。`);
  const sh = res.sihua;
  const has = ['禄', '权', '科', '忌'].filter(k => ZI_STARS[sh[k]]);
  if (has.length) {
    const txt = has.map(k => `${k}→${sh[k]}`).join('，');
    lines.push(`本年干化曜：${txt}。化禄是舒展之处，化忌是修习之处——都温柔待它。`);
  }
  lines.push('把这张盘当作一面镜子：看见自己的来处与质地，然后更松一点，照自己舒服的方式活。');
  return lines;
}
