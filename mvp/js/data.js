// 日期种子（当天固定）：用于「每日一抽 / 命理小语」稳定。Date 或字符串均可
function seedFromDate(d) {
  const s = (d instanceof Date) ? `${d.getFullYear()}-${d.getMonth() + 1}-${d.getDate()}` : String(d);
  let h = 2166136261;
  for (let i = 0; i < s.length; i++) { h ^= s.charCodeAt(i); h = Math.imul(h, 16777619); }
  return h >>> 0;
}

