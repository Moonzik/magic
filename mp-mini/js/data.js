// 给定目标选一段经文：seed 模式按种子稳定可复现（预置曲）；random 模式每次随机取一段（定制曲，保证每首不同）
function pickScripture(goal, seed, random) {
  const arr = SCRIPTURES_BY_GOAL[goal];
  if (!arr || !arr.length) return [];
  if (random) return arr[Math.floor(Math.random() * arr.length)];
  const i = (Math.abs(seed | 0) || 0) % arr.length;
  return arr[i];
}

